def get_scenario_by_id(scenario_id: str) -> dict[str, Any] | None:
    for ex in GOLD_EXEMPLARS:
        if ex["scenario_id"] == scenario_id:
            return ex
    return None


def get_exemplars_by_profile(profile: str) -> list[dict[str, Any]]:
    return [ex for ex in GOLD_EXEMPLARS if ex["tpa_executive_profile"] == profile]


def format_exemplars_for_prompt(limit: int = 4, profile: str | None = None) -> str:
    """Format gold exemplars as few-shot anchors for the LLM system prompt."""
    if profile:
        pool = get_exemplars_by_profile(profile)
    else:
        # One exemplar per profile for diversity when limit allows
        seen: set[str] = set()
        pool = []
        for ex in GOLD_EXEMPLARS:
            p = ex["tpa_executive_profile"]
            if p not in seen:
                seen.add(p)
                pool.append(ex)
        pool = pool or GOLD_EXEMPLARS

    lines: list[str] = []
    for ex in pool[:limit]:
        lines.append(f"--- {ex['scenario_id']} ({ex['tpa_executive_profile']}) ---")
        lines.append(f"Context: {ex['conversation_context']}")
        lines.append(f"AI Understanding: {ex['ai_understanding']}")
        lines.append(f"AI: {ex['ai_response']}")
        lines.append(f"Executive: {ex['executive_response']}")
        lines.append(f"Outcome: {ex['call_outcome']}")
        lines.append("")
    return "\n".join(lines)


def claim_context_block(
    hospital_name: str,
    claim_id: str,
    patient_name: str,
    claim_type: str,
    tpa_name: str = "",
    npi: str = "",
    policy_number: str = "",
    claim_age_days: int | None = None,
) -> str:
    """Build claim context injected into every prompt (RCM batch / ID&V fields)."""
    payer = tpa_name or "Not specified"
    age_line = (
        f"\n- Claim Age: {claim_age_days} days (RCM outstanding queue — follow-up required)"
        if claim_age_days is not None and claim_age_days > 0
        else "\n- Claim Age: Outstanding (RCM follow-up queue)"
    )
    return (
        f"## Active Claim Context (RCM Batch)\n"
        f"- Hospital: {hospital_name or 'Not specified'}\n"
        f"- Payer / Insurer: {payer}\n"
        f"- Claim Number: {claim_id or 'Not specified'}\n"
        f"- Patient: {patient_name or 'Not specified'}\n"
        f"- Claim Type / Status: {claim_type or 'Pending follow-up'}"
        f"{age_line}\n"
        f"- Provider NPI (for ID&V): {npi or 'Not specified'}\n"
        f"- Policy / Member Number (for ID&V): {policy_number or 'Not specified'}"
    )
