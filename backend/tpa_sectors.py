_SECTOR_BY_ID = {s["id"]: s for s in TPA_SECTORS}


def list_tpa_sectors() -> list[dict[str, Any]]:
    return list(TPA_SECTORS)


def get_tpa_sector(sector_id: str) -> dict[str, Any] | None:
    if not sector_id:
        return None
    return _SECTOR_BY_ID.get(sector_id.strip().lower())


def sector_context_block(
    sector_id: str,
    focus_topics: list[str] | None = None,
) -> str:
    """Prompt block injecting the selected TPA sector and optional focus topics."""
    sector = get_tpa_sector(sector_id)
    if not sector:
        return (
            "## TPA domain boundary\n"
            "Stay strictly within insurance TPA operations: eligibility, authorization, referrals, "
            "claims, payment, denials, appeals, records, COB, enrollment, patient responsibility, "
            "pharmacy, case management, utilization, admissions, discharge, cashless, packages, "
            "final bill, policy info, fraud, compliance, customer service, special programs, "
            "and specialty services. Decline non-TPA topics politely and return to the case."
        )

    topics = list(sector.get("topics") or [])
    samples = list(sector.get("sample_questions") or [])
    focus = [t for t in (focus_topics or []) if t]
    if not focus:
        focus = topics[:8]

    lines = [
        "## Active TPA sector for this call",
        f"Sector {sector['number']}: **{sector['name']}**",
        f"Purpose: {sector.get('description') or ''}",
        "",
        "### Topics in scope for this sector",
        ", ".join(topics),
        "",
        "### Focus for this call (prioritize these)",
        ", ".join(focus),
        "",
        "### Example questions (use as patterns only — invent natural wording each turn)",
    ]
    for q in samples:
        lines.append(f"- {q}")
    lines.extend(
        [
            "",
            "### Sector conversation rules (outbound provider caller)",
            f"- You call the payer and ASK dynamic questions about **{sector['name']}**.",
            "- Invent one natural question per turn from these topics + what the payer just said.",
            "- Sample questions above are patterns for meaning only — never read them as a fixed script.",
            "- Answer their verification requests from claim context; then resume sector questions.",
            "- Stay inside TPA domains; decline non-insurance topics politely.",
        ]
    )
    return "\n".join(lines)


def valid_sector_id(sector_id: str) -> bool:
    return get_tpa_sector(sector_id) is not None
